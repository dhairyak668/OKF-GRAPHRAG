# ── converter integration with parser ────────────────────────────


class TestOkfParserIntegration:
    """Verify that LLM-generated OKF content can be parsed by the parser."""

    def test_generated_content_has_valid_frontmatter(self):
        fm, body = parse_frontmatter(SAMPLE_OKF_RESPONSE)
        assert fm["type"] == "Tool"
        assert fm["title"] == "Sample Converted Library"
        assert "api" in fm["tags"]
        assert fm["status"] == "draft"
        assert "sources" in fm

    def test_generated_content_has_sources(self):
        fm, _ = parse_frontmatter(SAMPLE_OKF_RESPONSE)
        sources = fm["sources"]
        assert len(sources) >= 1
        assert sources[0]["resource"] == "/source_docs/sample-project/README.md"

    def test_generated_content_produces_chunks(self):
        _, body = parse_frontmatter(SAMPLE_OKF_RESPONSE)
        chunks = chunk_body(body)
        assert len(chunks) >= 1
        full_text = " ".join(c.text for c in chunks)
        assert "API Gateway" in full_text

    def test_generated_content_has_extractable_links(self):
        _, body = parse_frontmatter(SAMPLE_OKF_RESPONSE)
        links = extract_links(
            body,
            source_concept_id="libraries/sample-converted-library",
            bundle_root=BUNDLE_ROOT,
            source_file=BUNDLE_ROOT / "libraries" / "sample-converted-library.md",
        )
        target_ids = {link.target_concept_id for link in links}
        assert "services/api-gateway" in target_ids
        assert "services/auth-service" in target_ids
        assert "workflows/event-processing" in target_ids


# ── single document conversion (mocked LLM) ─────────────────────


class TestConvertDocument:

    def _make_mock_client(self, response_text: str) -> MagicMock:
        mock_response = MagicMock()
        mock_response.choices = [MagicMock()]
        mock_response.choices[0].message.content = response_text
        mock_client = MagicMock()
        mock_client.chat.completions.create.return_value = mock_response
        return mock_client

    def test_convert_single_document(self, tmp_path):
        raw_doc = tmp_path / "raw" / "test-project" / "README.md"
        raw_doc.parent.mkdir(parents=True)
        raw_doc.write_text("# Test Project\n\nA test project for unit testing.\n\n## Features\n\n- Feature 1\n- Feature 2\n")

        bundle = tmp_path / "bundle"
        bundle.mkdir()
        (bundle / "services").mkdir()

        mock_client = self._make_mock_client(SAMPLE_OKF_RESPONSE)

        result = convert_document(
            raw_path=raw_doc,
            bundle_root=bundle,
            output_name="test-project.md",
            output_subdir="libraries",
            client=mock_client,
        )

        assert result.output_path == bundle / "libraries" / "test-project.md"
        assert result.concept_id == "libraries/test-project"
        assert result.output_path.exists()
        assert "services/api-gateway" in result.links_to

    def test_convert_auto_derives_name(self, tmp_path):
        raw_doc = tmp_path / "My_Cool_Project.md"
        raw_doc.write_text("# My Cool Project\n\nSome content here that is long enough.\n")

        bundle = tmp_path / "bundle"
        bundle.mkdir()

        mock_client = self._make_mock_client(SAMPLE_OKF_RESPONSE)

        result = convert_document(
            raw_path=raw_doc,
            bundle_root=bundle,
            client=mock_client,
        )

        assert "my-cool-project" in result.concept_id

    def test_convert_dry_run_does_not_write(self, tmp_path):
        raw_doc = tmp_path / "test.md"
        raw_doc.write_text("# Test\n\nContent for testing the dry run feature.\n")

        bundle = tmp_path / "bundle"
        bundle.mkdir()

        mock_client = self._make_mock_client(SAMPLE_OKF_RESPONSE)

        result = convert_document(
            raw_path=raw_doc,
            bundle_root=bundle,
            client=mock_client,
            dry_run=True,
        )

        assert not result.output_path.exists()
        assert result.okf_content == SAMPLE_OKF_RESPONSE

    def test_convert_strips_code_fences(self, tmp_path):
        raw_doc = tmp_path / "test.md"
        raw_doc.write_text("# Test\n\nSome content.\n")

        bundle = tmp_path / "bundle"
        bundle.mkdir()

        fenced = f"```markdown\n{SAMPLE_OKF_RESPONSE}\n```"
        mock_client = self._make_mock_client(fenced)

        result = convert_document(
            raw_path=raw_doc,
            bundle_root=bundle,
            client=mock_client,
            dry_run=True,
        )

        assert result.okf_content.startswith("---")
        assert "```markdown" not in result.okf_content

    def test_convert_sends_concept_list_to_llm(self, tmp_path):
        raw_doc = tmp_path / "test.md"
        raw_doc.write_text("# Test\n\nSome content.\n")

        mock_client = self._make_mock_client(SAMPLE_OKF_RESPONSE)

        convert_document(
            raw_path=raw_doc,
            bundle_root=BUNDLE_ROOT,
            client=mock_client,
            dry_run=True,
        )

        call_args = mock_client.chat.completions.create.call_args
        messages = call_args.kwargs.get("messages") or call_args[1].get("messages")
        user_msg = messages[1]["content"]
        assert "services/api-gateway" in user_msg
        assert "services/auth-service" in user_msg
        assert "Existing concepts in the bundle" in user_msg


# ── batch conversion (mocked LLM) ───────────────────────────────


class TestConvertBatch:

    def _make_mock_client(self, response_text: str) -> MagicMock:
        mock_response = MagicMock()
        mock_response.choices = [MagicMock()]
        mock_response.choices[0].message.content = response_text
        mock_client = MagicMock()
        mock_client.chat.completions.create.return_value = mock_response
        return mock_client

    def test_batch_converts_multiple_files(self, tmp_path):
        raw_dir = tmp_path / "raw"
        raw_dir.mkdir()
        for name in ["project-a.md", "project-b.md", "project-c.md"]:
            (raw_dir / name).write_text(f"# {name}\n\nContent for {name} that is long enough to pass the filter.\n")

        bundle = tmp_path / "bundle"
        bundle.mkdir()

        mock_client = self._make_mock_client(SAMPLE_OKF_RESPONSE)

        result = convert_batch(
            paths=[raw_dir],
            bundle_root=bundle,
            client=mock_client,
        )

        assert len(result.converted) == 3
        assert len(result.errors) == 0

    def test_batch_skips_short_files(self, tmp_path):
        raw_dir = tmp_path / "raw"
        raw_dir.mkdir()
        (raw_dir / "short.md").write_text("# Hi\n")
        (raw_dir / "long.md").write_text("# Long\n\n" + "Content that is definitely long enough.\n" * 5)

        bundle = tmp_path / "bundle"
        bundle.mkdir()

        mock_client = self._make_mock_client(SAMPLE_OKF_RESPONSE)

        result = convert_batch(
            paths=[raw_dir],
            bundle_root=bundle,
            client=mock_client,
        )

        assert len(result.converted) == 1
        assert len(result.skipped) == 1
        assert "Too short" in result.skipped[0][1]

    def test_batch_accumulates_concepts(self, tmp_path):
        """Later conversions in a batch see concepts from earlier ones."""
        raw_dir = tmp_path / "raw"
        raw_dir.mkdir()
        (raw_dir / "first.md").write_text("# First\n\nFirst project documentation with enough content.\n")
        (raw_dir / "second.md").write_text("# Second\n\nSecond project documentation with enough content.\n")

        bundle = tmp_path / "bundle"
        bundle.mkdir()

        call_count = {"n": 0}
        concept_lists_seen: list[str] = []

        def capture_call(**kwargs):
            messages = kwargs.get("messages", [])
            user_msg = messages[1]["content"] if len(messages) > 1 else ""
            concept_lists_seen.append(user_msg)
            call_count["n"] += 1
            mock_resp = MagicMock()
            mock_resp.choices = [MagicMock()]
            mock_resp.choices[0].message.content = SAMPLE_OKF_RESPONSE
            return mock_resp

        mock_client = MagicMock()
        mock_client.chat.completions.create.side_effect = capture_call

        convert_batch(
            paths=[raw_dir],
            bundle_root=bundle,
            client=mock_client,
        )

        assert call_count["n"] == 2
        # The second call should contain the concept generated from the first
        assert "libraries/first" in concept_lists_seen[1] or "Sample Converted Library" in concept_lists_seen[1]

    def test_batch_handles_mixed_paths(self, tmp_path):
        raw_dir = tmp_path / "raw"
        raw_dir.mkdir()
        file_a = raw_dir / "standalone.md"
        file_a.write_text("# Standalone\n\nA standalone raw doc with enough content to convert.\n")

        subdir = raw_dir / "subproject"
        subdir.mkdir()
        (subdir / "intro.md").write_text("# Intro\n\nIntroduction document with substantial content here.\n")

        bundle = tmp_path / "bundle"
        bundle.mkdir()

        mock_client = self._make_mock_client(SAMPLE_OKF_RESPONSE)

        result = convert_batch(
            paths=[file_a, subdir],
            bundle_root=bundle,
            client=mock_client,
        )

        assert len(result.converted) == 2

    def test_batch_dry_run(self, tmp_path):
        raw_dir = tmp_path / "raw"
        raw_dir.mkdir()
        (raw_dir / "test.md").write_text("# Test\n\nContent for testing the dry run batch mode.\n")

        bundle = tmp_path / "bundle"
        bundle.mkdir()

        mock_client = self._make_mock_client(SAMPLE_OKF_RESPONSE)

        result = convert_batch(
            paths=[raw_dir],
            bundle_root=bundle,
            client=mock_client,
            dry_run=True,
        )

        assert len(result.converted) == 1
        assert not result.converted[0].output_path.exists()


# ── reingest integration test ────────────────────────────────────


class TestReingestIntegration:
    """Verify that converted OKF files can be ingested by the ingestion pipeline."""

    def test_converted_file_can_be_ingested(self, tmp_path):
        from okf_graphrag.ingestion import ingest_bundle
        from okf_graphrag.graph.store import KnowledgeGraph

        bundle = tmp_path / "bundle"
        (bundle / "libraries").mkdir(parents=True)

        (bundle / "libraries" / "sample-library.md").write_text(SAMPLE_OKF_RESPONSE + "\n")

        db_path = tmp_path / "test.db"
        with KnowledgeGraph(db_path) as store:
            result = ingest_bundle(bundle, store)

        assert result["files_found"] == 1
        assert result["updated"] == 1

        with KnowledgeGraph(db_path) as store:
            node = store.get_node("libraries/sample-library")
            assert node is not None
            assert node["type"] == "Tool"
            assert node["title"] == "Sample Converted Library"

            neighbors = store.get_neighbors("libraries/sample-library")
            outgoing_ids = {n["concept_id"] for n in neighbors["outgoing"]}
            assert "services/api-gateway" in outgoing_ids
            assert "services/auth-service" in outgoing_ids

            chunks = store.get_chunks("libraries/sample-library")
            assert len(chunks) >= 1
